const DICTS: Record<string, Dict> = { en, vi, es, pt, id, fr, de, ja, ko };

let dict: Dict = en;
let current = 'en';

export function setLanguage(tag: string): void {
  const base = (tag || 'en').toLowerCase().split(/[-_]/)[0];
  current = DICTS[base] ? base : 'en';
  dict = DICTS[current];
  document.documentElement.lang = current;
}

export function language(): string {
  return current;
}

export type TextKey = keyof Dict;

export function t(key: TextKey): string {
  return dict[key] ?? en[key];
}

const nf = new Map<string, Intl.NumberFormat>();
export function fmt(n: number): string {
  let f = nf.get(current);
  if (!f) nf.set(current, (f = new Intl.NumberFormat(current)));
  return f.format(n);
}
